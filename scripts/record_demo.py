def localize(lines, language):
    if language == "zh-CN":
        return list(lines)
    translated = []
    for line in lines:
        for original, replacement in EN_REPLACEMENTS:
            line = line.replace(original, replacement)
        if re.search(r"[\u4e00-\u9fff]", line):
            raise ValueError(f"Untranslated terminal text: {line}")
        translated.append(line)
    return translated


def render(lines, stage, font, language, progress=None):
    im = Image.new("RGB", (WIDTH, HEIGHT), "#0b1020")
    d = ImageDraw.Draw(im)
    title_font = ImageFont.truetype(font, 32)
    text_font = ImageFont.truetype(font, 22)
    small_font = ImageFont.truetype(font, 19)
    d.text((48, 26), "MINI RL TEACHER", font=title_font, fill="#edf3ff")
    d.text((48, 70), stage, font=small_font, fill="#a5b5d5")
    d.rounded_rectangle((28, 112, WIDTH - 28, 925), 16, fill="#141c2e", outline="#34415c")
    d.text((52, 125), "$ python mini_rl_teacher.py", font=small_font, fill="#8cdda9")
    for row, line in enumerate(lines):
        x, y = 52, 165 + row * 28
        if y > 895:
            raise ValueError("Terminal output would be cropped")
        for ch in line:
            cells = 2 if unicodedata.east_asian_width(ch) in ("F", "W") else 1
            color = {"·": "#65728b", "▼": "#ff7b86", "●": "#7be0aa", "★": "#7be0aa"}.get(ch, "#e1e8f5")
            if x + cells * 14 > WIDTH - 48:
                raise ValueError(f"Terminal line is too wide to render: {line}")
            d.text((x, y), ch, font=text_font, fill=color)
            x += cells * 14
    d.text((48, 948), UI[language]["footer"], font=small_font, fill="#9eacc7")
    if progress is not None:
        d.rectangle((28, 916, 28 + (WIDTH - 56) * progress, 920), fill="#7be0aa")
    return im


def encode_language(output, intro, frames, final, font, language):
    ui = UI[language]
    scenes = [(intro, ui["pretrain"], 100, None)]
    scenes += [(lines, ui["training"].format(count=len(frames)), 8, i / (len(frames) - 1))
               for i, lines in enumerate(frames)]
    scenes += [(final, ui["evaluation"], 175, None)]
    scenes = [(localize(lines, language), stage, repeat, progress)
              for lines, stage, repeat, progress in scenes]
    mp4 = output / f"mini-rl-teacher.{language}.mp4"
    cmd = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-f", "rawvideo",
           "-pix_fmt", "rgb24", "-s", f"{WIDTH}x{HEIGHT}", "-r", str(FPS), "-i", "-",
           "-an", "-c:v", "libx264", "-preset", "medium", "-crf", "20", "-pix_fmt",
           "yuv420p", "-movflags", "+faststart", str(mp4)]
    with subprocess.Popen(cmd, stdin=subprocess.PIPE) as encoder:
        try:
            for lines, stage, repeat, progress in scenes:
                data = render(lines, stage, font, language, progress).tobytes()
                for _ in range(repeat):
                    encoder.stdin.write(data)
            encoder.stdin.close()
        except Exception:
            encoder.kill()
            raise
        if encoder.wait():
            raise RuntimeError("ffmpeg encoding failed")
    render(localize(frames[-1], language), ui["poster"], font, language, 1).save(
        output / f"poster.{language}.png")
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(mp4),
                    "-filter_complex", "fps=5,scale=864:-1:flags=lanczos,split[a][b];"
                    "[a]palettegen=stats_mode=diff[p];[b][p]paletteuse=dither=bayer",
                    "-loop", "0", str(output / f"preview.{language}.gif")], check=True)
    return sum(s[2] for s in scenes) / FPS


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--replay", type=Path, help="Existing raw or plain Chinese UTF-8 stdout log")
    ap.add_argument("--font", help="Chinese-capable font path")
    ap.add_argument("--output", type=Path, default=ROOT / "docs/demo")
    ap.add_argument("--language", choices=["en", "zh-CN", "both"], default="both")
    args = ap.parse_args()
    font = find_font(args.font)
    args.output.mkdir(parents=True, exist_ok=True)
    source = ROOT / "mini_rl_teacher.py"
    recording = None
    if args.replay:
        raw = args.replay.read_bytes().decode("utf-8")
        provenance = args.replay.parent / "run.json"
        if provenance.exists():
            recording = json.loads(provenance.read_text(encoding="utf-8"))
    else:
        print("Running the unmodified default training script...", flush=True)
        completed = subprocess.run([sys.executable, "-u", str(source)], cwd=ROOT,
                                   stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        if completed.returncode:
            sys.stderr.buffer.write(completed.stderr)
            raise SystemExit(completed.returncode)
        raw = completed.stdout.decode("utf-8")
    clean, intro, frames, final = parse_output(raw)
    transcript_hash = hashlib.sha256(clean.encode("utf-8")).hexdigest()
    if recording and recording["terminal_sha256"] != transcript_hash:
        raise ValueError("Replay transcript does not match the adjacent run.json")
    if recording is None:
        recording = {
            "source": "mini_rl_teacher.py",
            "source_sha256": None if args.replay else hashlib.sha256(source.read_bytes()).hexdigest(),
            "terminal_sha256": transcript_hash,
            "training_command": None if args.replay else f"{Path(sys.executable).name} -u mini_rl_teacher.py",
            "python": None if args.replay else platform.python_version(),
            "numpy": None if args.replay else __import__("numpy").__version__,
            "training_frames": len(frames),
            "evaluation_stdout": final,
            "note": "Original captured stdout. In replay mode, missing provenance is left unknown.",
        }
    (args.output / "terminal.txt").write_text(clean, encoding="utf-8")
    (args.output / "run.json").write_text(json.dumps(recording, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    languages = ["en", "zh-CN"] if args.language == "both" else [args.language]
    for language in languages:
        print(f"Rendering {language}...", flush=True)
        seconds = encode_language(args.output, intro, frames, final, font, language)
        if language == "en":
            translated = "\n".join(localize(clean.splitlines(), language)) + "\n"
            (args.output / "terminal.en.txt").write_text(translated, encoding="utf-8")
        metadata = {
            "language": language, "original_terminal_sha256": transcript_hash,
            "renderer_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            "python": platform.python_version(), "pillow": pillow_version,
            "training_frames": len(frames), "video_seconds": seconds,
            "timing": "Pretraining 4s, each printed training frame 0.32s, evaluation 7s; not real-time",
            "presentation": "English translation of original stdout" if language == "en" else "Original Chinese stdout with Chinese presentation text",
            "assets": {},
        }
        for filename in [f"mini-rl-teacher.{language}.mp4", f"preview.{language}.gif", f"poster.{language}.png"]:
            metadata["assets"][filename] = hashlib.sha256((args.output / filename).read_bytes()).hexdigest()
        (args.output / f"media.{language}.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
        print(json.dumps({"language": language, "seconds": seconds, "frames": len(frames)}), flush=True)


if __name__ == "__main__":
    main()
